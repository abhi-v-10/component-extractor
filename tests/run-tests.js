/**
 * Comprehensive Automated Test Suite for Component Extractor
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

let testsPassed = 0;
let testsFailed = 0;

function assert(condition, message) {
  if (!condition) {
    console.error(`  ❌ FAILED: ${message}`);
    testsFailed++;
  } else {
    console.log(`  ✓ PASSED: ${message}`);
    testsPassed++;
  }
}

console.log('🧪 Starting Component Extractor Test Suite...\n');

// ==========================================
// Test 1: Manifest V3 Compliance
// ==========================================
console.log('1. Testing Manifest V3 & Firefox / Zen Browser Compatibility:');
const manifestPath = path.join(__dirname, '..', 'component-extractor', 'manifest.json');
assert(fs.existsSync(manifestPath), 'manifest.json exists');

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
assert(manifest.manifest_version === 3, 'Manifest version is 3');
assert(manifest.browser_specific_settings?.gecko?.id != null, 'Gecko extension ID is defined for Zen/Firefox');
assert(manifest.browser_specific_settings?.gecko?.strict_min_version != null, 'Gecko strict_min_version is defined');
assert(manifest.background?.scripts?.includes('background.js'), 'background.scripts contains background.js');
assert(manifest.permissions?.includes('activeTab') && manifest.permissions?.includes('scripting'), 'Permissions are minimal (activeTab, scripting)');

// Check all 4 icons exist
const iconSizes = ['16', '32', '48', '128'];
for (const s of iconSizes) {
  const iconRel = manifest.icons?.[s];
  assert(iconRel != null && fs.existsSync(path.join(__dirname, '..', 'component-extractor', iconRel)), `Icon ${s}px exists at ${iconRel}`);
}

// ==========================================
// Test 2: In-Browser Pure JS ZipBuilder
// ==========================================
console.log('\n2. Testing ZipBuilder Archive Generation:');
const { ZipBuilder } = require('../component-extractor/src/utils/zip-builder.js');

const zip = new ZipBuilder();
const testHtml = '<!DOCTYPE html><html><body><div class="card">Card Text</div></body></html>';
const testCss = '.card { background: #1e1e2e; color: #fff; padding: 16px; border-radius: 8px; }';
const testReadme = '# Test Component\nGenerated by Component Extractor';

zip.addFile('index.html', testHtml);
zip.addFile('style.css', testCss);
zip.addFile('README.md', testReadme);

const zipBytes = zip.buildUint8Array();
assert(zipBytes.length > 0, `Generated ZIP buffer (${zipBytes.length} bytes)`);

// Verify with Python zipfile
const tempZipPath = path.join('/tmp', `ce_test_${Date.now()}.zip`);
fs.writeFileSync(tempZipPath, Buffer.from(zipBytes));

try {
  const pyVerify = `
import zipfile
with zipfile.ZipFile("${tempZipPath}", "r") as zf:
    names = zf.namelist()
    assert "index.html" in names, "missing index.html"
    assert "style.css" in names, "missing style.css"
    assert "README.md" in names, "missing README.md"
    html_content = zf.read("index.html").decode("utf-8")
    assert "Card Text" in html_content, "corrupted index.html content"
    css_content = zf.read("style.css").decode("utf-8")
    assert "border-radius" in css_content, "corrupted style.css content"
`;
  execSync(`python3 -c '${pyVerify}'`);
  assert(true, 'ZIP validated by Python zipfile: all files and content intact');
} catch (e) {
  assert(false, 'ZIP validation failed: ' + e.message);
} finally {
  if (fs.existsSync(tempZipPath)) fs.unlinkSync(tempZipPath);
}

// ==========================================
// Test 3: CSS Extractor & Filtering
// ==========================================
console.log('\n3. Testing CSS Extractor & URL Resolution:');
const {
  formatStylesToCssRules,
  resolveCssUrls,
  DEFAULT_VALUES
} = require('../component-extractor/src/extractor/css-extractor.js');

assert(DEFAULT_VALUES['position'] === 'static', 'Default position is static');
assert(DEFAULT_VALUES['opacity'] === '1', 'Default opacity is 1');

const formatted = formatStylesToCssRules('.card', {
  'display': 'flex',
  'padding': '16px',
  'color': '#ffffff'
});
assert(formatted.includes('.card {') && formatted.includes('display: flex;') && formatted.includes('color: #ffffff;'), 'Formatted CSS rule correctly');

const resolvedUrl = resolveCssUrls('url("../images/hero.png")', 'https://example.com/assets/css/style.css');
assert(resolvedUrl === 'url("https://example.com/assets/images/hero.png")', 'Relative CSS URL correctly resolved to absolute');

// ==========================================
// Test 4: HTML Generator & Packaging
// ==========================================
console.log('\n4. Testing HTML Generator & Indenter:');
const { indentHtml, generateComponentPackage } = require('../component-extractor/src/generators/html-generator.js');

const rawSnippet = '<div class="btn"><span>Click Me</span></div>';
const indented = indentHtml(rawSnippet);
assert(indented.includes('  <span>Click Me</span>'), 'HTML properly indented with 2 spaces');

// Mock cloned root
const mockClonedRoot = {
  outerHTML: '<div class="ce-card"><h3>Title</h3><p>Desc</p></div>'
};
const pkg = generateComponentPackage(mockClonedRoot, ['.ce-card { padding: 12px; }'], {
  title: 'Test Card',
  fonts: ['Inter', 'Roboto']
});

assert(pkg.standaloneHtml.includes('<!DOCTYPE html>'), 'Generated standalone HTML contains DOCTYPE');
assert(pkg.standaloneHtml.includes('fonts.googleapis.com'), 'Includes Google Fonts import for Inter/Roboto');
assert(pkg.componentCss.includes('.ce-card { padding: 12px; }'), 'Includes extracted component CSS');

// ==========================================
// Test 5: Phase 2 Architecture Stubs
// ==========================================
console.log('\n5. Testing Phase 2 React & Tailwind Stubs:');
const { ReactGenerator } = require('../component-extractor/src/generators/react-generator.js');
const { TailwindGenerator } = require('../component-extractor/src/generators/tailwind-generator.js');

const reactGen = new ReactGenerator({ componentName: 'HeroWidget' });
const reactRes = reactGen.generate({
  componentHtml: '<div class="banner"><label for="email">Email</label><img src="pic.jpg"></div>'
});
assert(reactRes.jsxCode.includes('export default function HeroWidget'), 'Generated React component function export');
assert(reactRes.jsxCode.includes('className="banner"'), 'Mapped class to className');
assert(reactRes.jsxCode.includes('htmlFor="email"'), 'Mapped for to htmlFor');
assert(reactRes.jsxCode.includes('<img src="pic.jpg" />'), 'Self-closed void img tag');

const twGen = new TailwindGenerator();
const twClasses = twGen.mapStylesToTailwind({
  'display': 'flex',
  'flex-direction': 'column',
  'align-items': 'center',
  'padding': '16px',
  'font-weight': '700'
});
assert(twClasses.includes('flex'), 'Mapped display: flex -> flex');
assert(twClasses.includes('flex-col'), 'Mapped flex-direction: column -> flex-col');
assert(twClasses.includes('items-center'), 'Mapped align-items: center -> items-center');
assert(twClasses.includes('p-4'), 'Mapped padding: 16px -> p-4');
assert(twClasses.includes('font-bold'), 'Mapped font-weight: 700 -> font-bold');

// ==========================================
// Summary
// ==========================================
console.log('\n----------------------------------------');
console.log(`Results: ${testsPassed} passed, ${testsFailed} failed.`);
if (testsFailed > 0) {
  console.error('❌ Test suite failed!');
  process.exit(1);
} else {
  console.log('🎉 ALL TESTS PASSED SUCCESSFULLY!');
}
